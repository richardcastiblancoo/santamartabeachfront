        function initMobileMenu() {
            const menuBtn = document.getElementById("menu-btn");
            const mobileMenu = document.getElementById("mobile-menu");
            const menuIcon = document.getElementById("menu-icon");

            if (!menuBtn || !mobileMenu || !menuIcon) return;

            function toggleMenu(show) {
                const isCurrentlyHidden = mobileMenu.classList.contains("hidden");
                const shouldShow = show !== undefined ? show : isCurrentlyHidden;

                if (shouldShow) {
                    mobileMenu.classList.remove("hidden");
                    menuIcon.textContent = "close";
                } else {
                    mobileMenu.classList.add("hidden");
                    menuIcon.textContent = "menu";
                }
            }

            menuBtn.addEventListener("click", (e) => {
                e.preventDefault();
                e.stopPropagation();
                toggleMenu();
            });

            mobileMenu.querySelectorAll("a").forEach((link) => {
                link.addEventListener("click", () => toggleMenu(false));
            });

            document.addEventListener("click", (e) => {
                if (!mobileMenu.contains(e.target) && !menuBtn.contains(e.target)) {
                    toggleMenu(false);
                }
            });

            document.addEventListener("keydown", (e) => {
                if (e.key === "Escape") {
                    toggleMenu(false);
                }
            });
        }

        function initQRCode() {
            const qrContainer = document.getElementById("qrcode-footer");
            if (qrContainer && typeof QRCode !== "undefined") {
                qrContainer.innerHTML = "";
                new QRCode(qrContainer, {
                    text: "https://share.google/7p47kpoNR6FN3WJRe",
                    width: 130,
                    height: 130,
                    colorDark: "#101c22",
                    colorLight: "#ffffff",
                    correctLevel: QRCode.CorrectLevel.H,
                });
            }
        }

        function initYear() {
            const yearEl = document.getElementById("current-year");
            if (yearEl) {
                yearEl.textContent = new Date().getFullYear();
            }
        }

        function changeLanguage(lang) {
            if (!translations[lang]) return;

            document.documentElement.lang = lang;

            document.querySelectorAll("[data-key]").forEach((el) => {
                const key = el.getAttribute("data-key");
                if (translations[lang][key] !== undefined) {
                    el.innerHTML = translations[lang][key];
                }
            });

            document.querySelectorAll(".flag-btn").forEach((btn) => {
                btn.classList.remove("flag-active");
                const btnLang = btn.dataset.lang || btn.id;
                if (btnLang && btnLang.includes(lang)) {
                    btn.classList.add("flag-active");
                }
            });

            renderRestaurants(lang);
        }

        function initLanguageSelector() {
            document.querySelectorAll(".flag-btn").forEach((btn) => {
                btn.addEventListener("click", (e) => {
                    e.preventDefault();
                    const lang = btn.dataset.lang || btn.id.split("-").pop();
                    if (lang && translations[lang]) {
                        changeLanguage(lang);
                    }
                });
            });
        }

        function renderRestaurants(lang) {
            const grid = document.getElementById("restaurant-grid");
            if (!grid || !translations[lang] || !translations[lang].restaurants) return;

            grid.innerHTML = "";

            translations[lang].restaurants.forEach((res, index) => {
                const card = document.createElement("div");
                card.className =
                    "restaurant-card bg-white dark:bg-gray-950 border border-gray-100 dark:border-gray-900 p-8 rounded-xl flex flex-col justify-between gap-4";

                const cleanTel = res.tel.replace(/[^0-9]/g, "");
                const telHTML =
                    res.tel !== "N/A" && cleanTel.length >= 7 ?
                    `<a href="tel:+57${cleanTel}" class="hover:text-accent transition-colors">${res.tel}</a>` :
                    res.tel;

                card.innerHTML = `
      <div>
        <h3 class="font-display text-2xl font-bold text-black dark:text-white mb-3">${res.name}</h3>
        <div class="space-y-2">
          <p class="text-gray-500 dark:text-gray-400 text-xs flex items-start gap-2 leading-relaxed">
            <span class="material-symbols-outlined !text-base text-accent shrink-0 mt-0.5">location_on</span> 
            <span>${res.addr}</span>
          </p>
          <p class="text-gray-400 text-xs tracking-wide flex items-center gap-2">
            <span class="material-symbols-outlined !text-base text-blue-400 shrink-0">call</span> 
            <span>${telHTML}</span>
          </p>
        </div>
      </div>
    `;

                grid.appendChild(card);

                requestAnimationFrame(() => {
                    setTimeout(() => card.classList.add("visible"), 20 + index * 30);
                });
            });
        }

