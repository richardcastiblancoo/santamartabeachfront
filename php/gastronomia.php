    <script>
        function toggleMobileMenu() {
            const menu = document.getElementById('mobile-menu');
            const icon = document.getElementById('menu-icon');
            if (menu) {
                menu.classList.toggle('hidden');
                if (icon) {
                    if (menu.classList.contains('hidden')) {
                        icon.className = 'fa-solid fa-bars text-2xl';
                    } else {
                        icon.className = 'fa-solid fa-xmark text-2xl';
                    }
                }
            }
        }

        function toggleDeskLang() {
            const dropdown = document.getElementById('dropdown-desk');
            if (dropdown) dropdown.classList.toggle('hidden');
        }

        function selectLanguage(lang) {
            const flags = {
                es: "https://flagcdn.com/w80/co.png",
                en: "https://flagcdn.com/w80/us.png",
                fr: "https://flagcdn.com/w80/fr.png",
                it: "https://flagcdn.com/w80/it.png",
                pt: "https://flagcdn.com/w80/pt.png"
            };

            const shortLabels = {
                es: "ES",
                en: "EN",
                fr: "FR",
                it: "IT",
                pt: "PT"
            };

            const flagDesk = document.getElementById('flag-desk');
            const labelDesk = document.getElementById('label-desk');
            if (flagDesk) flagDesk.src = flags[lang];
            if (labelDesk) labelDesk.textContent = shortLabels[lang];

            const dropdownDesk = document.getElementById('dropdown-desk');
            if (dropdownDesk) dropdownDesk.classList.add('hidden');

            const mobileMenu = document.getElementById('mobile-menu');
            const icon = document.getElementById('menu-icon');
            if (mobileMenu && !mobileMenu.classList.contains('hidden')) {
                mobileMenu.classList.add('hidden');
                if (icon) icon.className = 'fa-solid fa-bars text-2xl';
            }

            localStorage.setItem('preferred_language', lang);

            if (typeof translations !== 'undefined' && translations[lang]) {
                document.querySelectorAll('[data-key]').forEach(el => {
                    const key = el.getAttribute('data-key');
                    if (translations[lang][key]) {
                        el.textContent = translations[lang][key];
                    }
                });
            }
        }

        document.addEventListener('DOMContentLoaded', () => {
            const savedLang = localStorage.getItem('preferred_language') || 'es';
            selectLanguage(savedLang);

            if (document.getElementById("qrcode-footer")) {
                new QRCode(document.getElementById("qrcode-footer"), {
                    text: "https://g.page/r/tu-enlace-de-google",
                    width: 90,
                    height: 90
                });
            }
        });
    </script>

